/***************************
 * `\\` — жёсткий перенос строки.
 **************************/
import { h } from '../../core/dom'
import { latexCommands } from '../registry'
import { MQSymbol } from './core'

/**
 * Рисуется как `<br>` внутри пустого span.
 *
 * `<br>` — форсированный разрыв, он срабатывает даже в корневом блоке с
 * `white-space: nowrap`, поэтому переносу не нужно ни менять раскладку блока,
 * ни знать о ней. Span нужен затем, что узлу требуется элемент с коробкой:
 * по нему `MQSymbol.seek` считает, с какой стороны кликнули, а курсор
 * вставляет себя относительно него.
 */
export class Linebreak extends MQSymbol {
    constructor() {
        super('\\\\', h('span', { class: 'mq-linebreak' }, [h('br')]))
    }
}

/**
 * Парсер отдаёт в реестр управляющую последовательность без ведущей обратной
 * косой, так что именем для `\\` оказывается одиночная косая. Остальные —
 * псевдонимы для набора через `\имя`.
 */
latexCommands.define(['\\', 'newline', 'linebreak', 'cr'], () => new Linebreak())
